package codegen

import (
	"fmt"
	"path"
	"path/filepath"
	"strings"
)

// kotlin writes one enum class per kind of slug, with the slug as its
// value.
//
// The Voidhash SDK for Android takes slugs as String (presentFlow(activity,
// placement), hasActivePerk(slug), a product's slug), so the constants are
// passed by value and the file needs no import. The type names end in Slug
// because the SDK has its own VoidhashProduct.
type kotlin struct{}

func (kotlin) Language() string { return Kotlin }

func (kotlin) Emit(schema Schema, options Options) string {
	file := path.Base(filepath.ToSlash(options.Output))
	lines := []string{"// " + file + " — generated by voidhash, do not edit"}
	lines = append(lines, markers(options)...)
	lines = append(lines,
		"//",
		"// The slugs of the project's products, paywall locations and perks, as types.",
		"// The Voidhash SDK takes a slug as a String: pass a constant's value, for example",
		"//",
		"//   voidhash.presentFlow(activity, VoidhashLocationSlug.ONBOARDING.value)",
		"//   voidhash.getProducts().first { it.slug == VoidhashProductSlug.PRO_MONTHLY.value }",
		"//   person.hasActivePerk(VoidhashPerkSlug.PRO.value)",
		"//",
		"// A slug that is not a Kotlin name is spelled as one (pro-monthly is PRO_MONTHLY), and",
		"// slugs that would share a name are numbered in the order of the slugs.",
		"//",
		"// Run `voidhash types generate` again when the project's products, locations or perks",
		"// change; `voidhash types check` fails while this file is behind.",
	)
	packageName := options.Package
	if packageName == "" {
		packageName = KotlinPackage(options.Output)
	}
	if packageName != "" {
		lines = append(lines, "", "package "+packageName)
	}
	if len(schema.Flows) > 0 {
		// The flow types build on the SDK's; a project without them needs no import.
		lines = append(lines, "",
			"import com.voidhash.sdk.FlowActionHandler",
			"import com.voidhash.sdk.FlowActions",
			"import com.voidhash.sdk.FlowInput",
			"import com.voidhash.sdk.FlowLocation",
			"import com.voidhash.sdk.FlowResult",
			"import com.voidhash.sdk.NoFlowActions",
			"import com.voidhash.sdk.NoFlowInput",
		)
	}
	lines = append(lines, kotlinEnum("VoidhashProductSlug", "products", schema.Products)...)
	lines = append(lines, kotlinEnum("VoidhashLocationSlug", "paywall locations", schema.Locations)...)
	lines = append(lines, kotlinEnum("VoidhashPerkSlug", "perks", schema.Perks)...)
	lines = append(lines, kotlinFlows(schema.Flows)...)
	lines = append(lines, "")
	return strings.Join(lines, "\n")
}

// KotlinPackage is the package of a Kotlin file at output, by the Gradle
// convention: the directories below the last `java` or `kotlin` source
// directory. It is empty when the path has no such directory or one of the
// directories is not a package name.
func KotlinPackage(output string) string {
	directories := strings.Split(path.Dir(filepath.ToSlash(output)), "/")
	root := -1
	for index, directory := range directories {
		if directory == "java" || directory == "kotlin" {
			root = index
		}
	}
	if root < 0 || root == len(directories)-1 {
		return ""
	}
	parts := directories[root+1:]
	for _, part := range parts {
		for index := 0; index < len(part); index++ {
			char := part[index]
			letter := char == '_' || (char >= 'a' && char <= 'z') || (char >= 'A' && char <= 'Z')
			if !letter && (index == 0 || char < '0' || char > '9') {
				return ""
			}
		}
		if part == "" {
			return ""
		}
	}
	return strings.Join(parts, ".")
}

func kotlinEnum(name, what string, slugs []string) []string {
	lines := []string{
		"",
		"/** The slugs of the project's " + what + ". */",
		"enum class " + name + "(val value: String) {",
	}
	names := identifiers(slugs, upperSnake, "SLUG", "_", nil)
	for index, slug := range slugs {
		literal := quoted(slug, true, func(char rune) string { return fmt.Sprintf(`\u%04X`, char) })
		lines = append(lines, "    "+names[index]+"("+literal+"),")
	}
	return append(lines,
		"    ;",
		"",
		"    override fun toString(): String = value",
		"",
		"    companion object {",
		"        /** The constant of a slug, or null when the project had no such slug when this file was generated. */",
		"        fun fromValue(value: String): "+name+"? = values().firstOrNull { it.value == value }",
		"    }",
		"}",
	)
}
