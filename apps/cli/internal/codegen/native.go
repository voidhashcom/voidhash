// The kinds of a native component's value types.
const (
	nativeString  = "string"
	nativeNumber  = "number"
	nativeBoolean = "boolean"
	// nativeProduct is a product: the product's details when read, its id
	// when written or emitted.
	nativeProduct = "product"
	nativeEnum    = "enum"
	nativeList    = "list"
)

// NativeType is the type of a value a native component's view exchanges
// with the flow.
type NativeType struct {
	// Kind is "string", "number", "boolean", "product", "enum" or "list".
	Kind string
	// Options are an enum's values.
	Options []string
	// Of is the type of a list's items, which is not a list.
	Of *NativeType
}

// NativeProp is a property a native component's view reads.
type NativeProp struct {
	Key  string
	Type NativeType
	// Writable is false for a property the flow computes.
	Writable bool
}

// NativeField is a field of a native component event's payload.
type NativeField struct {
	Key  string
	Type NativeType
}

// NativeEvent is an event a native component's view emits.
type NativeEvent struct {
	Key     string
	Payload []NativeField
}

// NativePaywall is a paywall whose deployed release uses a native
// component's contract.
type NativePaywall struct {
	Slug string
	Name string
}

// NativeComponent is the contract of a component designed in the editor
// and rendered by the app's own view (docs/specs/native-rendering.md), as
// the project's schema lists it: one per name and version.
type NativeComponent struct {
	// Name is the native name the designer gave it.
	Name string
	// ID is "native/<name>", which the view is registered under.
	ID string
	// Version names the contract; a view of another version is not shown.
	Version  string
	Props    []NativeProp
	Events   []NativeEvent
	Paywalls []NativePaywall
}

// WithNativeComponents adds the project's native components, in any order.
func (schema Schema) WithNativeComponents(components []NativeComponent) Schema {
	sorted := slices.Clone(components)
	slices.SortStableFunc(sorted, func(a, b NativeComponent) int {
		if order := strings.Compare(a.Name, b.Name); order != 0 {
			return order
		}
		return strings.Compare(a.Version, b.Version)
	})
	schema.NativeComponents = sorted
	return schema
}

// NativeConflict is a native component's name that paywalls use at more
// than one version. One view of an app implements one version, so it cannot
// serve them all, and no bindings are generated while the conflict lasts.
type NativeConflict struct {
	Name string
	// Versions are the contracts sharing the name, each with its paywalls.
	Versions []NativeComponent
}

// NativeConflicts are the names of the schema's native components that
// more than one version shares, by name.
func NativeConflicts(schema Schema) []NativeConflict {
	var conflicts []NativeConflict
	for _, component := range schema.NativeComponents {
		if last := len(conflicts) - 1; last >= 0 && conflicts[last].Name == component.Name {
			conflicts[last].Versions = append(conflicts[last].Versions, component)
			continue
		}
		conflicts = append(conflicts, NativeConflict{Name: component.Name, Versions: []NativeComponent{component}})
	}
	return slices.DeleteFunc(conflicts, func(conflict NativeConflict) bool { return len(conflict.Versions) < 2 })
}

// nativeOutput is the file of the native bindings beside the type file at
// output: VoidhashTypes+NativeComponents.swift beside VoidhashTypes.swift,
// VoidhashTypesNativeComponents.kt beside VoidhashTypes.kt.
func nativeOutput(output, joiner string) string {
	extension := path.Ext(filepath.ToSlash(output))
	return strings.TrimSuffix(output, extension) + joiner + "NativeComponents" + extension
}

// nativeHeader is the header of a native bindings file.
func nativeHeader(output string, options Options, register []string) []string {
	lines := []string{"// " + path.Base(filepath.ToSlash(output)) + " — generated by voidhash, do not edit"}
	lines = append(lines, markers(options)...)
	lines = append(lines,
		"//",
		"// The project's components designed in the editor and marked for native rendering, as",
		"// types for the app's own views of them. Implement a component's Component and register",
		"// it with the renderer, for example",
		"//",
	)
	lines = append(lines, register...)
	return append(lines,
		"//",
		"// A view serves every paywall whose component has its name and its contract's version;",
		"// paywalls with another version show the component as designed. Run `voidhash types",
		"// generate` again when a deployed paywall changes a component's properties or events;",
		"// `voidhash types check` fails while this file is behind.",
	)
}

// nativeTypeNames names each component's namespace: SeatStepperNative for
// "seat-stepper".
func nativeTypeNames(components []NativeComponent, reserved map[string]bool) []string {
	names := make([]string, len(components))
	for index, component := range components {
		names[index] = component.Name
	}
	names = identifiers(names, upperCamel, "Component", "", reserved)
	for index := range names {
		names[index] += "Native"
	}
	return names
}

// capitalized is a key with its first letter capital: count is Count.
func capitalized(key string) string {
	if key == "" {
		return key
	}
	return strings.ToUpper(key[:1]) + key[1:]
}

// nativeEnumType is an enum type a component's bindings declare: for a property
// or a payload field whose type is an enum or a list of one.
type nativeEnumType struct {
	Name    string
	Options []string
}

// nativeEnums names the enum types of a component, by the property key or
// "<event>.<field>" they are for. Names other members of the namespace
// already take are in reserved.
func nativeEnums(component NativeComponent, reserved map[string]bool) map[string]nativeEnumType {
	var keys, bases []string
	var options [][]string
	add := func(key, base string, kind NativeType) {
		if kind.Kind == nativeList && kind.Of != nil {
			kind = *kind.Of
		}
		if kind.Kind != nativeEnum {
			return
		}
		keys = append(keys, key)
		bases = append(bases, base)
		options = append(options, kind.Options)
	}
	for _, prop := range component.Props {
		add(prop.Key, prop.Key, prop.Type)
	}
	for _, event := range component.Events {
		for _, field := range event.Payload {
			add(event.Key+"."+field.Key, event.Key+"-"+field.Key, field.Type)
		}
	}
	names := identifiers(bases, upperCamel, "Value", "", reserved)
	enums := make(map[string]nativeEnumType, len(keys))
	for index, key := range keys {
		enums[key] = nativeEnumType{Name: names[index], Options: options[index]}
	}
	return enums
}

// usesProducts reports whether any component has a product value, which
// the file then declares a type for.
func usesProducts(components []NativeComponent) bool {
	isProduct := func(kind NativeType) bool {
		return kind.Kind == nativeProduct || (kind.Kind == nativeList && kind.Of != nil && kind.Of.Kind == nativeProduct)
	}
	for _, component := range components {
		for _, prop := range component.Props {
			if isProduct(prop.Type) {
				return true
			}
		}
		for _, event := range component.Events {
			for _, field := range event.Payload {
				if isProduct(field.Type) {
					return true
				}
			}
		}
	}
	return false
}

// usedBy names the paywalls using a contract for a doc comment.
func usedBy(paywalls []NativePaywall) string {
	slugs := make([]string, len(paywalls))
	for index, paywall := range paywalls {
		slugs[index] = paywall.Slug
	}
	if len(slugs) == 0 {
		return ""
	}
	return ", used by " + strings.Join(slugs, ", ")
}

// The product fields componentProps carries besides the id, each text or
// absent.
var nativeProductFields = []string{"title", "price", "period", "trial", "currency"}

// --- Swift ------------------------------------------------------------------

// Companion is the Swift file of the project's native components, which
// imports the paywall UI module the type file must not need: none when the
// project has none, or when paywalls disagree on one (see
// [NativeConflicts]). Its path is given either way, so an outdated one can
// be removed.
func (swift) Companion(schema Schema, options Options) (Companion, bool) {
	output := nativeOutput(options.Output, "+")
	if len(schema.NativeComponents) == 0 || len(NativeConflicts(schema)) > 0 {
		return Companion{Output: output}, false
	}
	return Companion{Output: output, Content: swiftNativeFile(schema.NativeComponents, options, output)}, true
}

func swiftNativeFile(components []NativeComponent, options Options, output string) string {
	names := nativeTypeNames(components, swiftReserved)
	example := strings.TrimSuffix(names[0], "Native") + "View"
	lines := nativeHeader(output, options, []string{
		"//   final class " + example + ": " + names[0] + ".Component { … }",
		"//   options.flowRenderer = try FlowViewRenderer(registrations: [",
		"//       " + names[0] + ".registration(" + example + ".self),",
		"//   ])",
	})
	// The flow renderer's native component APIs are SPI, and so is what is
	// written against them.
	lines = append(lines, "", "#if os(iOS)", "    import UIKit", "    @_spi(NativeComponents) import VoidhashUI")
	if usesProducts(components) {
		lines = append(lines, swiftNativeProduct()...)
	}
	for index, component := range components {
		lines = append(lines, swiftNativeComponent(names[index], component)...)
	}
	return strings.Join(append(lines, "#endif", ""), "\n")
}

func swiftNativeProduct() []string {
	lines := []string{
		"",
		"    /// A product as a native component's properties carry it.",
		"    @_spi(NativeComponents)",
		"    public struct VoidhashNativeProduct: Equatable, Sendable {",
		"        /// The id the component writes and emits to name the product.",
		"        public var id: String",
	}
	for _, field := range nativeProductFields {
		lines = append(lines, "        public var "+field+": String?")
	}
	lines = append(lines,
		"",
		"        /// The product `value` holds; nil for no product.",
		"        public init?(_ value: VoidhashNativeComponentValue?) {",
		`            guard let id = value?["id"]?.string else { return nil }`,
		"            self.id = id",
	)
	for _, field := range nativeProductFields {
		lines = append(lines, fmt.Sprintf("            %s = value?[%q]?.string", field, field))
	}
	return append(lines, "        }", "    }")
}

// swiftRead is the type a value of kind is read as, and how it is read out
// of an optional VoidhashNativeComponentValue named source.
func swiftRead(kind NativeType, enum string, source string) (string, string) {
	switch kind.Kind {
	case nativeNumber:
		return "Double", source + "?.number ?? 0"
	case nativeBoolean:
		return "Bool", source + "?.bool ?? false"
	case nativeProduct:
		return "VoidhashNativeProduct?", "VoidhashNativeProduct(" + source + ")"
	case nativeEnum:
		return enum, enum + "(rawValue: " + source + "?.string ?? \"\")"
	case nativeList:
		of := NativeType{Kind: nativeString}
		if kind.Of != nil {
			of = *kind.Of
		}
		switch of.Kind {
		case nativeProduct:
			return "[VoidhashNativeProduct]", source + "?.array?.compactMap { VoidhashNativeProduct($0) } ?? []"
		case nativeEnum:
			return "[" + enum + "]", source + "?.array?.compactMap { $0.string.map(" + enum + ".init(rawValue:)) } ?? []"
		}
		item, _ := swiftRead(of, enum, "$0")
		accessor := map[string]string{nativeNumber: "number", nativeBoolean: "bool"}[of.Kind]
		if accessor == "" {
			accessor = "string"
		}
		return "[" + item + "]", source + "?.array?.compactMap(\\." + accessor + ") ?? []"
	default:
		return "String", source + "?.string ?? \"\""
	}
}

// swiftWrite is the type a value of kind is written or emitted as, and the
// VoidhashNativeComponentValue of the Swift value named value.
func swiftWrite(kind NativeType, enum string, value string) (string, string) {
	switch kind.Kind {
	case nativeNumber:
		return "Double", ".number(" + value + ")"
	case nativeBoolean:
		return "Bool", ".bool(" + value + ")"
	case nativeEnum:
		return enum, ".string(" + value + ".rawValue)"
	case nativeList:
		of := NativeType{Kind: nativeString}
		if kind.Of != nil {
			of = *kind.Of
		}
		item, encoded := swiftWrite(of, enum, "$0")
		return "[" + item + "]", ".array(" + value + ".map { " + encoded + " })"
	default:
		// Text, and a product by its id.
		return "String", ".string(" + value + ")"
	}
}

// idParameter is the name of a parameter for key: a product is passed by
// its id (planId), a list of them by their ids (addOnsIds).
func idParameter(key string, kind NativeType) string {
	if kind.Kind == nativeProduct {
		return key + "Id"
	}
	if kind.Kind == nativeList && kind.Of != nil && kind.Of.Kind == nativeProduct {
		return key + "Ids"
	}
	return key
}

// setterParameter is the name of a setter's parameter: productId for a
// product, productIds for a list of them, else value.
func setterParameter(kind NativeType) string {
	switch idParameter("product", kind) {
	case "productId":
		return "productId"
	case "productIds":
		return "productIds"
	}
	return "value"
}

func swiftNativeComponent(name string, component NativeComponent) []string {
	enums := nativeEnums(component, reservedSet("Props", "Context", "Component", "Adapter", "VoidhashNativeProduct"))
	quote := func(text string) string {
		return quoted(text, false, func(char rune) string { return fmt.Sprintf(`\u{%X}`, char) })
	}
	lines := []string{
		"",
		"    /// The native component " + component.Name + usedBy(component.Paywalls) + ".",
		"    @_spi(NativeComponents)",
		"    public enum " + name + " {",
		"        /// The id the view is registered under.",
		"        public static let definitionId = " + quote(component.ID),
		"        /// The contract this code implements; paywalls with another one show the designed component.",
		"        public static let version = " + quote(component.Version),
	}

	for _, key := range enumKeys(enums) {
		enum := enums[key]
		cases := identifiers(enum.Options, lowerCamel, "option", "", reservedSet(append(mapKeys(swiftReserved), "unknown", "init")...))
		lines = append(lines, "", "        /// The values of "+strings.ReplaceAll(key, ".", "'s ")+".", "        public enum "+enum.Name+": Equatable, Sendable {")
		for index := range enum.Options {
			lines = append(lines, "            case "+cases[index])
		}
		lines = append(lines,
			"            /// A value that is none of the options above.",
			"            case unknown(String)",
			"",
			"            public init(rawValue: String) {",
			"                switch rawValue {",
		)
		for index, option := range enum.Options {
			lines = append(lines, "                case "+quote(option)+": self = ."+cases[index])
		}
		lines = append(lines, "                default: self = .unknown(rawValue)", "                }", "            }", "",
			"            public var rawValue: String {", "                switch self {")
		for index, option := range enum.Options {
			lines = append(lines, "                case ."+cases[index]+": return "+quote(option))
		}
		lines = append(lines, "                case .unknown(let value): return value", "                }", "            }", "        }")
	}

	// Props: what the flow gives the view.
	lines = append(lines, "", "        /// What the flow gives the view.", "        public struct Props: Equatable, Sendable {")
	var parameters, assignments, reads []string
	for _, prop := range component.Props {
		id := swiftName(prop.Key)
		kind, read := swiftRead(prop.Type, enums[prop.Key].Name, fmt.Sprintf("props[%q]", prop.Key))
		if !prop.Writable {
			lines = append(lines, "            /// Computed by the flow; the view cannot set it.")
		}
		lines = append(lines, "            public var "+id+": "+kind)
		parameters = append(parameters, id+": "+kind)
		assignments = append(assignments, "                self."+id+" = "+id)
		reads = append(reads, "                "+id+" = "+read)
	}
	lines = append(lines, "", "            public init("+strings.Join(parameters, ", ")+") {")
	lines = append(lines, assignments...)
	lines = append(lines, "            }", "")
	lines = append(lines,
		"            /// The properties the flow sent; one missing or of another type reads as empty.",
		"            public init(_ props: [String: VoidhashNativeComponentValue]) {",
	)
	lines = append(lines, reads...)
	lines = append(lines, "            }", "        }")

	// Context: the flow, as the view reaches it.
	lines = append(lines,
		"",
		"        /// The flow, as the view reaches it. The setters and emitters may be called from any thread.",
		"        public struct Context: Sendable {",
		"            /// The context the typed members below go through.",
		"            public let untyped: VoidhashNativeComponentContext",
		"",
		"            public init(_ untyped: VoidhashNativeComponentContext) {",
		"                self.untyped = untyped",
		"            }",
		"",
		"            /// The flow's locale, Reduce Motion setting, colour scheme and layout direction.",
		"            @MainActor public var environment: VoidhashNativeComponentEnvironment { untyped.environment }",
		"            /// The state the flow shows the component in, when its node names one.",
		"            @MainActor public var state: VoidhashNativeComponentValue? { untyped.state }",
		"            /// Whether the flow disables the component; it should then take no input.",
		"            @MainActor public var isDisabled: Bool { untyped.isDisabled }",
	)
	for _, prop := range component.Props {
		if !prop.Writable {
			continue
		}
		parameter := setterParameter(prop.Type)
		kind, encoded := swiftWrite(prop.Type, enums[prop.Key].Name, parameter)
		what := "Sets " + prop.Key
		if parameter != "value" {
			what += " to the products with the ids `" + parameter + "`"
			if prop.Type.Kind == nativeProduct {
				what = "Sets " + prop.Key + " to the product with the id `" + parameter + "`"
			}
		}
		lines = append(lines, "",
			"            /// "+what+"; the new value comes back in the next update.",
			fmt.Sprintf("            public func set%s(_ %s: %s) {", capitalized(prop.Key), parameter, kind),
			fmt.Sprintf("                untyped.write(%q, %s)", prop.Key, encoded),
			"            }",
		)
	}
	for _, event := range component.Events {
		var signature, payload []string
		for _, field := range event.Payload {
			label := swiftName(idParameter(field.Key, field.Type))
			kind, encoded := swiftWrite(field.Type, enums[event.Key+"."+field.Key].Name, label)
			signature = append(signature, label+": "+kind)
			payload = append(payload, fmt.Sprintf("%q: %s", field.Key, encoded))
		}
		call := fmt.Sprintf("untyped.emit(%q)", event.Key)
		if len(payload) > 0 {
			call = fmt.Sprintf("untyped.emit(%q, payload: [%s])", event.Key, strings.Join(payload, ", "))
		}
		lines = append(lines, "",
			"            /// Tells the flow "+event.Key+" happened; it runs what the paywall binds to it.",
			"            public func emit"+capitalized(event.Key)+"("+strings.Join(signature, ", ")+") {",
			"                "+call,
			"            }",
		)
	}
	lines = append(lines, "",
		"            /// Measures the view again, after its size changed without an update.",
		"            public func invalidateSize() {",
		"                untyped.invalidateSize()",
		"            }",
		"        }",
	)

	// Component: what the app implements.
	lines = append(lines,
		"",
		"        /// The app's view of the component.",
		"        @MainActor",
		"        public protocol Component: AnyObject {",
		"            /// Creates the view for one place a flow shows the component; update(props:) follows at once.",
		"            init(context: Context)",
		"            /// The view the flow shows, sized to the component's frame. Read once, after creation.",
		"            var view: UIView { get }",
		"            /// The flow's properties: once after creation, then whenever one, the state or the disabled flag changes.",
		"            func update(props: Props)",
		"            /// The environment changed; the context already holds it.",
		"            func environmentDidChange(_ environment: VoidhashNativeComponentEnvironment)",
		"            /// The flow no longer shows the component: release what it holds.",
		"            func dispose()",
		"        }",
		"",
		"        /// What the renderer registers the component with, for FlowViewRenderer(registrations:).",
		"        public static func registration<Implementation: Component>(",
		"            _ type: Implementation.Type",
		"        ) -> VoidhashNativeComponentRegistration {",
		"            registration { context in Implementation(context: context) }",
		"        }",
		"",
		"        /// What the renderer registers the component with, making each view with make.",
		"        public static func registration(",
		"            make: @escaping @MainActor @Sendable (Context) -> any Component",
		"        ) -> VoidhashNativeComponentRegistration {",
		"            VoidhashNativeComponentRegistration(",
		"                definitionId: definitionId, version: version,",
		"                make: { context in Adapter(make(Context(context))) })",
		"        }",
		"",
		"        @MainActor",
		"        private final class Adapter: VoidhashNativeComponentView {",
		"            private let component: any Component",
		"",
		"            init(_ component: any Component) {",
		"                self.component = component",
		"            }",
		"",
		"            var view: UIView { component.view }",
		"",
		"            func update(props: [String: VoidhashNativeComponentValue]) {",
		"                component.update(props: Props(props))",
		"            }",
		"",
		"            func environmentDidChange(_ environment: VoidhashNativeComponentEnvironment) {",
		"                component.environmentDidChange(environment)",
		"            }",
		"",
		"            func dispose() {",
		"                component.dispose()",
		"            }",
		"        }",
		"    }",
		"",
		"    @_spi(NativeComponents)",
		"    extension "+name+".Component {",
		"        public func environmentDidChange(_ environment: VoidhashNativeComponentEnvironment) {}",
		"",
		"        public func dispose() {}",
		"    }",
	)
	return lines
}

// enumKeys are the keys of a component's enum types, in order.
func enumKeys(enums map[string]nativeEnumType) []string {
	keys := make([]string, 0, len(enums))
	for key := range enums {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys
}

func mapKeys(set map[string]bool) []string {
	keys := make([]string, 0, len(set))
	for key := range set {
		keys = append(keys, key)
	}
	return keys
}

// --- Kotlin -----------------------------------------------------------------

// Companion is the Kotlin file of the project's native components, which
// imports the paywall UI module the type file must not need; see the Swift
// one.
func (kotlin) Companion(schema Schema, options Options) (Companion, bool) {
	output := nativeOutput(options.Output, "")
	if len(schema.NativeComponents) == 0 || len(NativeConflicts(schema)) > 0 {
		return Companion{Output: output}, false
	}
	return Companion{Output: output, Content: kotlinNativeFile(schema.NativeComponents, options, output)}, true
}

func kotlinNativeFile(components []NativeComponent, options Options, output string) string {
	names := nativeTypeNames(components, kotlinReserved)
	example := strings.TrimSuffix(names[0], "Native") + "View"
	lines := nativeHeader(output, options, []string{
		"//   FlowViewRenderer(components = listOf(",
		"//       " + names[0] + ".factory { context, component -> " + example + "(context, component) },",
		"//   ))",
	})
	// The flow renderer's native component APIs need an opt-in.
	lines = append(lines, "", "@file:OptIn(ExperimentalNativeComponents::class)")
	packageName := options.Package
	if packageName == "" {
		packageName = KotlinPackage(options.Output)
	}
	if packageName != "" {
		lines = append(lines, "", "package "+packageName)
	}
	lines = append(lines, "",
		"import android.view.View",
		"import com.voidhash.ui.ExperimentalNativeComponents",
		"import com.voidhash.ui.NativeComponent",
		"import com.voidhash.ui.NativeComponentContext",
		"import com.voidhash.ui.NativeComponentEnvironment",
		"import com.voidhash.ui.NativeComponentFactory",
	)
	if usesProducts(components) {
		lines = append(lines, kotlinNativeProduct()...)
	}
	for index, component := range components {
		lines = append(lines, kotlinNativeComponent(names[index], component)...)
	}
	return strings.Join(append(lines, ""), "\n")
}

func kotlinNativeProduct() []string {
	lines := []string{
		"",
		"/** A product as a native component's properties carry it; [id] is what the component writes and emits. */",
		"data class VoidhashNativeProduct(",
		"    val id: String,",
	}
	for _, field := range nativeProductFields {
		lines = append(lines, "    val "+field+": String?,")
	}
	lines = append(lines,
		") {",
		"    companion object {",
		"        /** The product [value] holds; null for no product. */",
		"        fun from(value: Any?): VoidhashNativeProduct? {",
		"            val fields = value as? Map<*, *> ?: return null",
		`            val id = fields["id"] as? String ?: return null`,
		"            return VoidhashNativeProduct(",
		"                id = id,",
	)
	for _, field := range nativeProductFields {
		lines = append(lines, fmt.Sprintf("                %s = fields[%q] as? String,", field, field))
	}
	return append(lines, "            )", "        }", "    }", "}")
}

// kotlinNativeRead is the type a value of kind is read as, and how it is
// read out of the Any? named source.
func kotlinNativeRead(kind NativeType, enum string, source string) (string, string) {
	switch kind.Kind {
	case nativeNumber:
		return "Double", "(" + source + " as? Number)?.toDouble() ?: 0.0"
	case nativeBoolean:
		return "Boolean", source + " as? Boolean ?: false"
	case nativeProduct:
		return "VoidhashNativeProduct?", "VoidhashNativeProduct.from(" + source + ")"
	case nativeEnum:
		return enum, enum + ".from(" + source + ")"
	case nativeList:
		of := NativeType{Kind: nativeString}
		if kind.Of != nil {
			of = *kind.Of
		}
		items := "(" + source + " as? List<*>)"
		switch of.Kind {
		case nativeProduct:
			return "List<VoidhashNativeProduct>", items + "?.mapNotNull { VoidhashNativeProduct.from(it) } ?: emptyList()"
		case nativeEnum:
			return "List<" + enum + ">", items + "?.filterIsInstance<String>()?.map { " + enum + ".from(it) } ?: emptyList()"
		case nativeNumber:
			return "List<Double>", items + "?.filterIsInstance<Number>()?.map { it.toDouble() } ?: emptyList()"
		case nativeBoolean:
			return "List<Boolean>", items + "?.filterIsInstance<Boolean>() ?: emptyList()"
		}
		return "List<String>", items + "?.filterIsInstance<String>() ?: emptyList()"
	default:
		return "String", source + " as? String ?: \"\""
	}
}

// kotlinNativeWrite is the type a value of kind is written or emitted as,
// and the plain value the host takes for the Kotlin value named value.
func kotlinNativeWrite(kind NativeType, enum string, value string) (string, string) {
	switch kind.Kind {
	case nativeNumber:
		return "Double", value
	case nativeBoolean:
		return "Boolean", value
	case nativeEnum:
		return enum, value + ".value"
	case nativeList:
		of := NativeType{Kind: nativeString}
		if kind.Of != nil {
			of = *kind.Of
		}
		item, _ := kotlinNativeWrite(of, enum, "it")
		if of.Kind == nativeEnum {
			return "List<" + item + ">", value + ".map { it.value }"
		}
		return "List<" + item + ">", value
	default:
		// Text, and a product by its id.
		return "String", value
	}
}

func kotlinNativeComponent(name string, component NativeComponent) []string {
	enums := nativeEnums(component, reservedSet("Props", "Context", "Component", "VoidhashNativeProduct"))
	quote := func(text string) string {
		return quoted(text, true, func(char rune) string { return fmt.Sprintf(`\u%04X`, char) })
	}
	lines := []string{
		"",
		"/** The native component " + component.Name + usedBy(component.Paywalls) + ". */",
		"object " + name + " {",
		"    /** The id the view is registered under. */",
		"    const val ID: String = " + quote(component.ID),
		"",
		"    /** The contract this code implements; paywalls with another one show the designed component. */",
		"    const val VERSION: String = " + quote(component.Version),
	}

	for _, key := range enumKeys(enums) {
		enum := enums[key]
		cases := identifiers(enum.Options, upperCamel, "Option", "", reservedSet("Unknown", "Companion"))
		lines = append(lines, "", "    /** The values of "+strings.ReplaceAll(key, ".", "'s ")+". */", "    sealed interface "+enum.Name+" {", "        val value: String", "")
		for index, option := range enum.Options {
			lines = append(lines, "        data object "+cases[index]+" : "+enum.Name+" {", "            override val value: String = "+quote(option), "        }", "")
		}
		lines = append(lines,
			"        /** A value that is none of the options above. */",
			"        data class Unknown(override val value: String) : "+enum.Name,
			"",
			"        companion object {",
			"            fun from(value: Any?): "+enum.Name+" = when (value) {",
		)
		for index, option := range enum.Options {
			lines = append(lines, "                "+quote(option)+" -> "+cases[index])
		}
		lines = append(lines, `                else -> Unknown(value as? String ?: "")`, "            }", "        }", "    }")
	}

	if len(component.Props) == 0 {
		// A data class needs a property.
		lines = append(lines, "", "    /** What the flow gives the view: the component has no properties. */", "    class Props {",
			"        companion object {",
			"            @Suppress(\"UNUSED_PARAMETER\")",
			"            fun from(props: Map<String, Any?>): Props = Props()",
			"        }", "    }")
	} else {
		lines = append(lines, "", "    /** What the flow gives the view. */", "    data class Props(")
		var reads []string
		for _, prop := range component.Props {
			kind, read := kotlinNativeRead(prop.Type, enums[prop.Key].Name, fmt.Sprintf("props[%q]", prop.Key))
			if !prop.Writable {
				lines = append(lines, "        /** Computed by the flow; the view cannot set it. */")
			}
			lines = append(lines, "        val "+kotlinName(prop.Key)+": "+kind+",")
			reads = append(reads, "                "+kotlinName(prop.Key)+" = "+read+",")
		}
		lines = append(lines, "    ) {", "        companion object {",
			"            /** The properties the flow sent; one missing or of another type reads as empty. */",
			"            fun from(props: Map<String, Any?>): Props = Props(")
		lines = append(lines, reads...)
		lines = append(lines, "            )", "        }", "    }")
	}

	lines = append(lines,
		"",
		"    /** The flow, as the view reaches it. The setters and emitters may be called on any thread. */",
		"    class Context(",
		"        /** The context the typed members below go through. */",
		"        val untyped: NativeComponentContext,",
		"    ) {",
		"        /** The settings the flow shows the component with. */",
		"        val environment: NativeComponentEnvironment get() = untyped.environment",
		"",
		"        /** The state the flow shows the component in, or null. */",
		"        val state: String? get() = untyped.state",
		"",
		"        /** Whether the flow disables the component; it should then take no input. */",
		"        val disabled: Boolean get() = untyped.disabled",
		"",
		"        /** Called on the main thread when the environment changes, before the update of the same change. */",
		"        var onEnvironmentChanged: ((NativeComponentEnvironment) -> Unit)?",
		"            get() = untyped.onEnvironmentChanged",
		"            set(value) {",
		"                untyped.onEnvironmentChanged = value",
		"            }",
	)
	for _, prop := range component.Props {
		if !prop.Writable {
			continue
		}
		parameter := setterParameter(prop.Type)
		kind, encoded := kotlinNativeWrite(prop.Type, enums[prop.Key].Name, parameter)
		what := "Sets " + prop.Key
		if parameter != "value" {
			what += " to the products with the ids [" + parameter + "]"
			if prop.Type.Kind == nativeProduct {
				what = "Sets " + prop.Key + " to the product with the id [" + parameter + "]"
			}
		}
		lines = append(lines, "",
			"        /** "+what+"; the new value comes back in the next update. */",
			fmt.Sprintf("        fun set%s(%s: %s) = untyped.write(%q, %s)", capitalized(prop.Key), parameter, kind, prop.Key, encoded),
		)
	}
	for _, event := range component.Events {
		var signature, payload []string
		for _, field := range event.Payload {
			label := kotlinName(idParameter(field.Key, field.Type))
			kind, encoded := kotlinNativeWrite(field.Type, enums[event.Key+"."+field.Key].Name, label)
			signature = append(signature, label+": "+kind)
			payload = append(payload, fmt.Sprintf("%q to %s", field.Key, encoded))
		}
		call := fmt.Sprintf("untyped.emit(%q)", event.Key)
		if len(payload) > 0 {
			call = fmt.Sprintf("untyped.emit(%q, mapOf(%s))", event.Key, strings.Join(payload, ", "))
		}
		lines = append(lines, "",
			"        /** Tells the flow "+event.Key+" happened; it runs what the paywall binds to it. */",
			"        fun emit"+capitalized(event.Key)+"("+strings.Join(signature, ", ")+") = "+call,
		)
	}
	lines = append(lines, "",
		"        /** Measures the view again, after its size changed without an update. */",
		"        fun invalidateSize() = untyped.invalidateSize()",
		"    }",
		"",
		"    /** The app's view of the component. */",
		"    interface Component {",
		"        /** The view the flow shows; read once, after the first update. */",
		"        val view: View",
		"",
		"        /** The flow's properties: first when the component is created, then whenever one changes. */",
		"        fun update(props: Props)",
		"",
		"        /** The flow no longer shows the component: release what it holds. */",
		"        fun dispose() {}",
		"    }",
		"",
		"    /** The factory to give FlowViewRenderer(components = …), making each view with [make]. */",
		"    fun factory(make: (context: android.content.Context, component: Context) -> Component): NativeComponentFactory =",
		"        object : NativeComponentFactory {",
		"            override val id: String = ID",
		"            override val version: String = VERSION",
		"",
		"            override fun create(context: android.content.Context, component: NativeComponentContext): NativeComponent {",
		"                val made = make(context, Context(component))",
		"                return object : NativeComponent {",
		"                    override val view: View get() = made.view",
		"",
		"                    override fun update(props: Map<String, Any?>) = made.update(Props.from(props))",
		"",
		"                    override fun dispose() = made.dispose()",
		"                }",
		"            }",
		"        }",
		"}",
	)
	return lines
}
