package codegen

import (
	"bytes"
	"encoding/json"
	"strings"
)

// typeScript writes the declaration file that fills the VoidhashRegister of
// each SDK the app depends on ([Options.Packages]), so the React Native
// SDK's hooks and methods accept only the project's slugs, and both SDKs
// only its flag keys. The header's first line is the one every version of
// the CLI wrote.
type typeScript struct{}

func (typeScript) Language() string { return TypeScript }

func (typeScript) Emit(schema Schema, options Options) string {
	lines := []string{"// voidhash.gen.d.ts — generated by voidhash-cli, do not edit"}
	lines = append(lines, markers(options)...)
	packages := options.Packages
	if len(packages) == 0 {
		packages = []string{ReactNativePackage}
	}
	for _, sdk := range packages {
		lines = append(lines, "")
		if sdk == WebPackage {
			lines = append(lines, tsWebBlock(schema)...)
		} else {
			lines = append(lines, tsReactNativeBlock(schema)...)
		}
	}
	lines = append(lines, "", "export {};", "")
	return strings.Join(lines, "\n")
}

// tsReactNativeBlock types the React Native SDK: slugs, each product by its
// type, flags, and the interface of the flow at each location.
func tsReactNativeBlock(schema Schema) []string {
	lines := []string{
		`declare module "@voidhash/react-native" {`,
		"  interface VoidhashRegister {",
		"    schema: {",
		"      products: " + union(schema.Products) + ";",
		"      locations: " + union(schema.Locations) + ";",
		"      perks: " + union(schema.Perks) + ";",
		"      flags: " + union(flagKeys(schema.Flags)) + ";",
		"    };",
		"    productTypes: {",
	}
	for _, slug := range schema.Products {
		if sdkType, ok := schema.ProductTypes[slug]; ok {
			lines = append(lines, "      "+jsStringLiteral(slug)+": "+jsStringLiteral(sdkType)+";")
		}
	}
	lines = append(lines, "    };")
	lines = append(lines, tsFlagValues(schema.Flags)...)
	lines = append(lines, tsFlows(schema.Flows)...)
	return append(lines, "  }", "}")
}

// tsWebBlock types the web SDK, which has flags but no products, locations
// or perks.
func tsWebBlock(schema Schema) []string {
	lines := []string{
		`declare module "@voidhash/web" {`,
		"  interface VoidhashRegister {",
		"    schema: {",
		"      flags: " + union(flagKeys(schema.Flags)) + ";",
		"    };",
	}
	lines = append(lines, tsFlagValues(schema.Flags)...)
	return append(lines, "  }", "}")
}

func flagKeys(flags []Flag) []string {
	keys := make([]string, len(flags))
	for index, flag := range flags {
		keys[index] = flag.Key
	}
	return keys
}

// tsFlagValues lists the text values of each flag whose variants have them.
func tsFlagValues(flags []Flag) []string {
	lines := []string{"    flagValues: {"}
	for _, flag := range flags {
		if len(flag.Values) > 0 {
			lines = append(lines, "      "+jsStringLiteral(flag.Key)+": "+union(flag.Values)+";")
		}
	}
	return append(lines, "    };")
}

// union is the type of one of the slugs: "a" | "b", or never without any.
func union(slugs []string) string {
	if len(slugs) == 0 {
		return "never"
	}
	literals := make([]string, len(slugs))
	for index, slug := range slugs {
		literals[index] = jsStringLiteral(slug)
	}
	return strings.Join(literals, " | ")
}

// jsStringLiteral quotes text as JavaScript's JSON.stringify does, which
// leaves <, >, & and the line separators as they are.
func jsStringLiteral(text string) string {
	var buffer bytes.Buffer
	encoder := json.NewEncoder(&buffer)
	encoder.SetEscapeHTML(false)
	// A string always encodes.
	_ = encoder.Encode(text)
	literal := strings.TrimSuffix(buffer.String(), "\n")
	literal = strings.ReplaceAll(literal, `\u2028`, "\u2028")
	return strings.ReplaceAll(literal, `\u2029`, "\u2029")
}

// Companion is the file holding the interface revisions, which a
// declaration file cannot export: voidhash.flows.gen.ts beside
// voidhash.gen.d.ts.
func (typeScript) Companion(schema Schema, options Options) (Companion, bool) {
	if len(schema.Flows) == 0 {
		return Companion{}, false
	}
	output := strings.TrimSuffix(strings.TrimSuffix(options.Output, ".d.ts"), ".gen") + ".flows.gen.ts"
	file := output[strings.LastIndexAny(output, `/\`)+1:]
	return Companion{Output: output, Content: tsRevisions(schema.Flows, options, file)}, true
}
