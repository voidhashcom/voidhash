package codegen

import (
	"fmt"
	"path"
	"path/filepath"
	"strings"
)

// swift writes one enum per kind of slug, with the slug as its raw value.
//
// The Voidhash SDK for Apple platforms takes slugs as String
// (presentFlow(location:), purchase(productSlug:), hasActivePerk(_:)), so
// the enums are passed by rawValue and the file needs no import. The type
// names end in Slug because the SDK has its own VoidhashProduct.
type swift struct{}

func (swift) Language() string { return Swift }

// swiftReserved are names a case cannot take as they are: keywords, and the
// members every such enum already has.
var swiftReserved = reservedSet(
	"allCases", "rawValue", "hashValue", "hash", "description",
	"associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init",
	"inout", "internal", "let", "open", "operator", "private", "precedencegroup", "protocol", "public",
	"rethrows", "static", "struct", "subscript", "typealias", "var", "break", "case", "catch", "continue",
	"default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in", "repeat", "return",
	"throw", "switch", "where", "while", "any", "as", "await", "false", "is", "nil", "self", "super",
	"throws", "true", "try", "none", "some", "type", "protocol",
)

func reservedSet(names ...string) map[string]bool {
	set := make(map[string]bool, len(names))
	for _, name := range names {
		set[name] = true
	}
	return set
}

func (swift) Emit(schema Schema, options Options) string {
	file := path.Base(filepath.ToSlash(options.Output))
	lines := []string{"// " + file + " — generated by voidhash, do not edit"}
	lines = append(lines, markers(options)...)
	lines = append(lines,
		"//",
		"// The slugs of the project's products, paywall locations and perks, as types.",
		"// The Voidhash SDK takes a slug as a String: pass a case's rawValue, for example",
		"//",
		"//   try await voidhash.presentFlow(location: VoidhashLocationSlug.onboarding.rawValue)",
		"//   try await voidhash.purchase(productSlug: VoidhashProductSlug.proMonthly.rawValue)",
		"//   person.hasActivePerk(VoidhashPerkSlug.pro.rawValue)",
		"//",
		"// A slug that is not a Swift name is spelled as one (pro-monthly is proMonthly), and",
		"// slugs that would share a name are numbered in the order of the slugs.",
		"//",
		"// Run `voidhash types generate` again when the project's products, locations or perks",
		"// change; `voidhash types check` fails while this file is behind.",
	)
	if len(schema.Flows) > 0 {
		// The flow types build on the SDK's; a project without them needs no import.
		lines = append(lines, "", "import Voidhash")
	}
	lines = append(lines, swiftEnum("VoidhashProductSlug", "products", schema.Products)...)
	lines = append(lines, swiftEnum("VoidhashLocationSlug", "paywall locations", schema.Locations)...)
	lines = append(lines, swiftEnum("VoidhashPerkSlug", "perks", schema.Perks)...)
	lines = append(lines, swiftFlows(schema.Flows)...)
	lines = append(lines, "")
	return strings.Join(lines, "\n")
}

func swiftEnum(name, what string, slugs []string) []string {
	if len(slugs) == 0 {
		// An enum without cases cannot have a raw type.
		return []string{
			"",
			"/// The slugs of the project's " + what + ": it has none yet.",
			"public enum " + name + ": Sendable {}",
		}
	}
	lines := []string{
		"",
		"/// The slugs of the project's " + what + ".",
		"public enum " + name + ": String, CaseIterable, Sendable {",
	}
	names := identifiers(slugs, lowerCamel, "slug", "", swiftReserved)
	for index, slug := range slugs {
		literal := quoted(slug, false, func(char rune) string { return fmt.Sprintf(`\u{%X}`, char) })
		lines = append(lines, "    case "+names[index]+" = "+literal)
	}
	return append(lines, "}")
}
