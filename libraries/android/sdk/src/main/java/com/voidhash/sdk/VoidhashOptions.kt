package com.voidhash.sdk

import com.voidhash.sdk.analytics.ScreenView
import com.voidhash.sdk.diagnostics.VoidhashDiagnostic
import com.voidhash.sdk.paywall.PaywallRenderer

/** SDK version reported through `x-sdk-version`; matches the npm package version. */
const val VOIDHASH_SDK_VERSION: String = "0.0.1-alpha.1"

/** Default Voidhash API origin. */
const val VOIDHASH_DEFAULT_BASE_URL: String = "https://api.voidhash.com"

/**
 * Prefix of every anonymous distinct id the SDK generates: `vh_anon_<uuid>`. It holds only
 * letters, digits, `_` and `-`, so the id fits any payment provider's field.
 */
const val ANONYMOUS_DISTINCT_ID_PREFIX: String = "vh_anon_"

/** Prefix of the anonymous ids earlier SDK builds generated, which a stored id may still carry. */
const val LEGACY_ANONYMOUS_DISTINCT_ID_PREFIX: String = "vh:anon:"

/** Whether [distinctId] was generated by the SDK, or an earlier build of it. */
fun isAnonymousDistinctId(distinctId: String): Boolean =
    distinctId.startsWith(ANONYMOUS_DISTINCT_ID_PREFIX) ||
        distinctId.startsWith(LEGACY_ANONYMOUS_DISTINCT_ID_PREFIX)

/**
 * Configuration for [Voidhash.configure].
 *
 * @property baseUrl origin of the Voidhash API.
 * @property ingestUrl origin of the analytics ingest API; defaults to [baseUrl].
 * @property debug forces `x-is-debug-build` and writes the SDK's warnings to logcat under the tag
 *   `Voidhash`. Off, the SDK writes nothing to logcat; [onDiagnostic] reports the same situations
 *   either way. No log line or diagnostic carries a user id or a purchase token.
 * @property distinctId pins the initial distinct id instead of generating an anonymous one.
 *   When it replaces an anonymous id this device already used, `initialize()` queues the
 *   alias, so that id's purchases and history merge into the pinned person. A blank value is
 *   ignored with a warning.
 * @property enabled when false, or when [Voidhash.configure] is given no publishable key, the client is inert: no network, no billing connection, no
 *   timers or callbacks, and nothing read from or written to storage, so what an enabled client
 *   stored earlier is kept untouched. Every method returns its documented empty value.
 *   `purchase` throws `CONFIGURATION_MISSING`.
 * @property readOnly observer mode — transactions are synced but never finished with the store,
 *   and purchases are refused, so another billing integration can own them. Off by default.
 * @property dev requests development mode. Honored only in debug builds: there purchases run
 *   against a mock store and are recorded under the development environment, never charged.
 *   In a release build (or with `dev = false`) the real Play Billing store is used.
 * @property screenTracking configures the automatic `$screen` event.
 * @property automaticLifecycleEvents captures `$app_installed`, `$app_updated`, `$app_opened`,
 *   `$app_backgrounded`, `$app_became_active`, `$app_crashed` and `$sign_out`. An app that reports
 *   these events itself turns it off.
 * @property preloadLocations locations whose flows are fetched and cached on the first launch,
 *   so a flow can be presented before the device has ever resolved it online. Locations the
 *   device has already resolved are remembered and preloaded without being listed here. Inert
 *   without a [paywallRenderer].
 * @property flowRevisions the revision of each location's interface the app was built against,
 *   by location slug. It is what [VoidhashClient.presentFlow] reports for a location when the
 *   call names no revision, and what preloading reports, so the flow fetched ahead is one this
 *   build of the app can run. A location without an entry counts as revision 0.
 * @property paywallRenderer draws flows. Add the `ui` module and pass
 *   `VoidhashUiPaywallRenderer()`; without a renderer, [VoidhashClient.presentFlow] throws
 *   [FlowFailure.RENDERER_MISSING]. Flow packages are downloaded, verified and cached for
 *   offline use.
 * @property flowCapabilities what flows may do beyond showing screens, purchasing and restoring.
 *   Only [FlowCapability.LINKS] is granted by default.
 * @property onDiagnostic receives structured reports about situations the SDK handled on its
 *   own: dropped events, an open circuit, a rejected key, an unreadable cache entry. Called on
 *   one background thread of the SDK's, in the order the reports were made, never on the
 *   thread that caused them; exceptions it raises are swallowed.
 * @property runInSecondaryProcess runs the SDK in a process other than the app's main one.
 *   Off by default: `configure` in any other process returns an inert client, as with
 *   `enabled = false`. The SDK's storage is not safe to share between processes, so turn this
 *   on only for an app whose UI runs in a named process and never configure Voidhash in more
 *   than one process of the app.
 * @property analyticsConsent the end user's consent to usage analytics on a device where the app
 *   has not called [VoidhashClient.setAnalyticsConsent] yet; once it has, the stored choice wins
 *   over this option on every later launch. Unless [AnalyticsConsent.GRANTED], no events, screens,
 *   or lifecycle events are collected. Purchases, entitlements, flags, paywalls,
 *   identify, person attributes and groups are unaffected.
 * @property analyticsWhilePending what happens to events captured while the consent is
 *   [AnalyticsConsent.PENDING]: dropped, or with [PendingAnalytics.BUFFER] held in memory until the
 *   end user decides.
 * @property grantConsentOnIdentify treats signing in as the end user's agreement: an
 *   [VoidhashClient.identify] made while the consent is [AnalyticsConsent.PENDING] grants it. A
 *   consent granted this way lasts until [VoidhashClient.signOut] or [VoidhashClient.reset], which
 *   return it to pending, or until the app calls [VoidhashClient.setAnalyticsConsent], whose
 *   decision stays. [AnalyticsConsent.DENIED] is never overridden. Off by default.
 * @property featureFlags how flag reads behave before an evaluation has arrived.
 * @property installAttribution reads which ad brought this install, once per install, in the
 *   background and only with analytics consent, and records it on the person as a touch: the Google
 *   Play install referrer, and Meta's apps when [metaAppId] is set. An install that predates this
 *   option is not read. On by default.
 * @property metaAppId the app's Meta (Facebook) app id. When set, [installAttribution] also asks the
 *   Facebook, Instagram and Facebook Lite apps installed on the device for the ad behind the install,
 *   which is preferred over the Play referrer.
 */
data class VoidhashOptions(
    val baseUrl: String = VOIDHASH_DEFAULT_BASE_URL,
    val ingestUrl: String? = null,
    val debug: Boolean = false,
    val distinctId: String? = null,
    val enabled: Boolean = true,
    val readOnly: Boolean = false,
    val dev: Boolean = false,
    val screenTracking: ScreenTrackingOptions = ScreenTrackingOptions(),
    val automaticLifecycleEvents: Boolean = true,
    val preloadLocations: List<String> = emptyList(),
    val flowRevisions: Map<String, Int> = emptyMap(),
    val paywallRenderer: PaywallRenderer? = null,
    val flowCapabilities: Set<FlowCapability> = setOf(FlowCapability.LINKS),
    val onDiagnostic: ((VoidhashDiagnostic) -> Unit)? = null,
    val runInSecondaryProcess: Boolean = false,
    val analyticsConsent: AnalyticsConsent = AnalyticsConsent.GRANTED,
    val featureFlags: FeatureFlagOptions = FeatureFlagOptions(),
    val installAttribution: Boolean = true,
    val metaAppId: String? = null,
    val analyticsWhilePending: PendingAnalytics = PendingAnalytics.DROP,
    val grantConsentOnIdentify: Boolean = false,
)

/**
 * How feature flag reads behave while no evaluation is cached.
 *
 * @property maxWaitMs how long a flag read with nothing cached waits for Voidhash before it
 *   answers without an evaluation. The evaluation carries on in the background; its answer is
 *   cached and published through [VoidhashClient.featureFlags]. A negative value counts as 0.
 * @property defaults the value a flag reads as while it has no evaluated value: in
 *   [VoidhashClient.isFeatureEnabled], and as a disabled or enabled flag without a variant in the
 *   results of [VoidhashClient.getFeatureFlags] for the keys it was asked for. A flag without an
 *   entry reads as disabled.
 */
data class FeatureFlagOptions(
    val maxWaitMs: Long = 2_000L,
    val defaults: Map<String, Boolean> = emptyMap(),
)

/**
 * Configuration of the automatic `$screen` event.
 *
 * @property automatic captures a screen for every resumed activity. Off, only
 *   [VoidhashClient.screen] and [VoidhashScreenTracking] produce screens.
 * @property fragments also captures resumed AndroidX fragments and suppresses the
 *   screen of the activities hosting them. Requires `androidx.fragment` on the classpath.
 * @property includeParams adds `$screen_params` (route arguments, string-coerced, at most
 *   20 keys). Off by default because arguments routinely carry ids and tokens.
 * @property mapScreen rewrites a screen before capture; returning `null` drops it.
 */
data class ScreenTrackingOptions(
    val automatic: Boolean = true,
    val fragments: Boolean = false,
    val includeParams: Boolean = false,
    val mapScreen: ((ScreenView) -> ScreenView?)? = null,
)
