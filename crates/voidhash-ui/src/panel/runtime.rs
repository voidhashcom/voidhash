//! Panel instances, UI state and the calls the host makes.

use alloc::boxed::Box;
use alloc::rc::Rc;
use alloc::vec::Vec;
use core::any::Any;
use core::cell::{Cell, RefCell};
use core::marker::PhantomData;
use core::ops::{Deref, DerefMut};

use crate::panel::context::{Context, Field, Layout, Locale, SelectedNode, StateOverride};
use crate::panel::host;
use crate::panel::intent::Intents;
use crate::panel::tree::{Handler, Panel};
use crate::value::Value;

/// A panel's render function, as `#[panel]` declares it.
pub type RenderFn = fn(&mut PanelCx) -> Panel;

/// A panel compiled into this module, generated by `#[panel]`.
pub struct PanelDefinition {
    /// The panel's id in the `vhp.panels` section.
    pub id: &'static str,
    /// The panel's `vhp.panels` entry as JSON.
    pub manifest: &'static str,
    /// Renders the panel.
    pub render: RenderFn,
}

struct Instance {
    render: RenderFn,
    context: RefCell<Rc<Value>>,
    hooks: RefCell<Vec<Option<Box<dyn Any>>>>,
    cursor: Cell<usize>,
    handlers: RefCell<Vec<Option<Handler>>>,
}

struct Runtime {
    instances: Vec<Option<Rc<Instance>>>,
    /// Buffers handed out by `vhp_alloc` that no call has consumed yet.
    #[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
    inputs: Vec<Box<[u8]>>,
    /// The result of the last `vhp_render` or `vhp_event`.
    #[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
    output: Vec<u8>,
}

impl Runtime {
    const fn new() -> Runtime {
        Runtime {
            instances: Vec::new(),
            inputs: Vec::new(),
            output: Vec::new(),
        }
    }
}

#[cfg(target_arch = "wasm32")]
mod global {
    use super::Runtime;
    use core::cell::RefCell;

    struct Single(RefCell<Runtime>);

    // SAFETY: panel modules run on one thread; the host never calls into
    // the module concurrently.
    unsafe impl Sync for Single {}

    static RUNTIME: Single = Single(RefCell::new(Runtime::new()));

    pub(super) fn with<R>(f: impl FnOnce(&mut Runtime) -> R) -> R {
        f(&mut RUNTIME.0.borrow_mut())
    }
}

#[cfg(not(target_arch = "wasm32"))]
mod global {
    use super::Runtime;
    use core::cell::RefCell;

    std::thread_local! {
        static RUNTIME: RefCell<Runtime> = const { RefCell::new(Runtime::new()) };
    }

    pub(super) fn with<R>(f: impl FnOnce(&mut Runtime) -> R) -> R {
        RUNTIME.with(|runtime| f(&mut runtime.borrow_mut()))
    }
}

/// Stops the module: logs `message` and traps. The host shows the panel's
/// error state and can restart the module.
#[cold]
pub(crate) fn fail(message: &str) -> ! {
    host::log(3, message);
    #[cfg(target_arch = "wasm32")]
    core::arch::wasm32::unreachable();
    #[cfg(not(target_arch = "wasm32"))]
    panic!("{message}");
}

fn instance(id: i32) -> Rc<Instance> {
    let found = global::with(|runtime| {
        usize::try_from(id)
            .ok()
            .and_then(|index| runtime.instances.get(index))
            .and_then(Option::clone)
    });
    found.unwrap_or_else(|| fail("unknown panel instance"))
}

fn decode_context(bytes: &[u8]) -> Option<Value> {
    match Value::decode(bytes) {
        Ok(context @ Value::Object(_)) => Some(context),
        _ => None,
    }
}

// Host calls -----------------------------------------------------------------------

/// `vhp_alloc`: a buffer of `size` bytes the host writes a call's input into.
#[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
pub(crate) fn alloc(size: usize) -> *mut u8 {
    let mut buffer = alloc::vec![0u8; size.max(1)].into_boxed_slice();
    let pointer = buffer.as_mut_ptr();
    global::with(|runtime| runtime.inputs.push(buffer));
    pointer
}

/// Takes back the `vhp_alloc` buffer at `pointer` once the host passes it to
/// a call. Input outside a buffer handed out by `vhp_alloc` is rejected.
#[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
pub(crate) fn take_input(pointer: *const u8, len: usize) -> Box<[u8]> {
    global::with(|runtime| {
        let index = runtime
            .inputs
            .iter()
            .position(|buffer| core::ptr::eq(buffer.as_ptr(), pointer) && len <= buffer.len());
        index.map(|index| runtime.inputs.swap_remove(index))
    })
    .unwrap_or_else(|| fail("call input was not allocated with vhp_alloc"))
}

/// `vhp_mount`: creates an instance of panel `index` of `panels` and returns
/// its id; `-1` when the context is not an encoded object and `-2` for an
/// unknown panel.
pub(crate) fn mount(panels: &[&PanelDefinition], index: i32, context: &[u8]) -> i32 {
    let Some(panel) = usize::try_from(index)
        .ok()
        .and_then(|index| panels.get(index))
    else {
        return -2;
    };
    let Some(context) = decode_context(context) else {
        return -1;
    };
    let instance = Rc::new(Instance {
        render: panel.render,
        context: RefCell::new(Rc::new(context)),
        hooks: RefCell::new(Vec::new()),
        cursor: Cell::new(0),
        handlers: RefCell::new(Vec::new()),
    });
    global::with(|runtime| {
        let slot = runtime.instances.iter().position(Option::is_none);
        let id = match slot {
            Some(slot) => {
                runtime.instances[slot] = Some(instance);
                slot
            }
            None => {
                runtime.instances.push(Some(instance));
                runtime.instances.len() - 1
            }
        };
        i32::try_from(id).unwrap_or(-3)
    })
}

/// `vhp_update`: replaces an instance's context. An invalid context traps.
pub(crate) fn update(id: i32, context: &[u8]) {
    let context = decode_context(context)
        .unwrap_or_else(|| fail("vhp_update context is not an encoded object"));
    *instance(id).context.borrow_mut() = Rc::new(context);
}

/// `vhp_render`: renders the instance and returns the encoded tree.
#[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
pub(crate) fn render(id: i32) -> (*const u8, usize) {
    let tree = render_value(id);
    finish_output(&tree)
}

/// Renders the instance into a tree value and keeps its handlers for
/// `vhp_event`.
pub(crate) fn render_value(id: i32) -> Value {
    let instance = instance(id);
    let context = instance.context.borrow().clone();
    instance.cursor.set(0);
    let mut cx = PanelCx {
        instance: id,
        context: Context { value: &context },
    };
    let root = (instance.render)(&mut cx);
    let mut handlers = Vec::new();
    let tree = crate::panel::tree::Node::from(root).encode(&mut handlers);
    *instance.handlers.borrow_mut() = handlers;
    tree
}

/// `vhp_event`: runs handler `handler` of the last tree with the event's
/// arguments and returns the encoded intents it recorded. An unknown handler
/// (from a tree the host has not replaced yet) records none.
#[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
pub(crate) fn event(id: i32, handler: i32, args: &[u8]) -> (*const u8, usize) {
    let args = match Value::decode(args) {
        Ok(Value::Array(args)) => args,
        _ => fail("vhp_event arguments are not an encoded array"),
    };
    let intents = event_value(id, handler, &args);
    finish_output(&intents)
}

/// Runs a handler and returns the intents it recorded.
pub(crate) fn event_value(id: i32, handler: i32, args: &[Value]) -> Value {
    let instance = instance(id);
    let index = usize::try_from(handler).unwrap_or(usize::MAX);
    let taken = instance
        .handlers
        .borrow_mut()
        .get_mut(index)
        .and_then(Option::take);
    let Some(action) = taken else {
        return Value::Array(Vec::new());
    };
    let context = instance.context.borrow().clone();
    let mut cx = EventCx {
        intents: Intents::default(),
        context: Context { value: &context },
    };
    action(&mut cx, args);
    if let Some(slot) = instance.handlers.borrow_mut().get_mut(index) {
        *slot = Some(action);
    }
    cx.intents.into_value()
}

/// `vhp_unmount`: frees the instance and its state.
pub(crate) fn unmount(id: i32) {
    let removed = global::with(|runtime| {
        usize::try_from(id)
            .ok()
            .and_then(|index| runtime.instances.get_mut(index))
            .and_then(Option::take)
    });
    // State and closures drop here, outside the runtime borrow.
    drop(removed);
}

#[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]
fn finish_output(value: &Value) -> (*const u8, usize) {
    let mut out = global::with(|runtime| core::mem::take(&mut runtime.output));
    out.clear();
    value.encode(&mut out);
    let result = (out.as_ptr(), out.len());
    global::with(|runtime| runtime.output = out);
    result
}

// Contexts -------------------------------------------------------------------------

/// What a panel renders from: the selection it edits and its UI state.
pub struct PanelCx<'a> {
    instance: i32,
    context: Context<'a>,
}

impl<'a> PanelCx<'a> {
    /// The selected nodes the panel applies to, in selection order.
    pub fn selection(&self) -> impl Iterator<Item = SelectedNode<'a>> {
        self.context.selection()
    }

    /// How many selected nodes the panel applies to.
    pub fn count(&self) -> usize {
        self.context.selection().count()
    }

    /// A prop of the panel's definition across the selection.
    pub fn prop(&self, name: &str) -> Field<'a> {
        self.context.prop(name)
    }

    /// A style key the panel declared, across the selection.
    pub fn style(&self, key: &str) -> Field<'a> {
        self.context.style(key)
    }

    /// The state whose overrides are being edited, if any.
    pub fn state_override(&self) -> Option<StateOverride<'a>> {
        self.context.state_override()
    }

    /// The locale the document is edited in.
    pub fn locale(&self) -> Locale<'a> {
        self.context.locale()
    }

    /// Where the selected nodes sit on the canvas. Empty unless the panel
    /// declared `context("layout")`.
    pub fn layout(&self) -> Layout<'a> {
        self.context.layout()
    }

    /// The value the panel last stored with
    /// [`Intents::set_ui`](crate::panel::Intents::set_ui), or null.
    pub fn ui(&self) -> &'a Value {
        self.context.get("ui")
    }

    /// Any context field by name, for fields added after this crate.
    pub fn raw(&self, key: &str) -> &'a Value {
        self.context.get(key)
    }

    /// State that persists across renders while the panel stays mounted,
    /// such as an open tab. `init` runs on the first render only.
    ///
    /// Like hooks in React, call `ui_state` unconditionally and in the same
    /// order on every render.
    pub fn ui_state<T: 'static>(&mut self, init: impl FnOnce() -> T) -> UiState<T> {
        let instance = instance(self.instance);
        let slot = instance.cursor.get();
        instance.cursor.set(slot + 1);
        let existing = instance
            .hooks
            .borrow()
            .get(slot)
            .map(|hook| hook.as_ref().is_some_and(|value| value.is::<T>()));
        match existing {
            Some(true) => {}
            Some(false) => fail("ui_state hooks must run in the same order on every render"),
            None => {
                let value: Box<dyn Any> = Box::new(init());
                instance.hooks.borrow_mut().push(Some(value));
            }
        }
        UiState {
            instance: self.instance,
            slot,
            _value: PhantomData,
        }
    }
}

fn with_hook<T: 'static, R>(instance_id: i32, slot: usize, f: impl FnOnce(&mut T) -> R) -> R {
    let instance = instance(instance_id);
    let taken = instance
        .hooks
        .borrow_mut()
        .get_mut(slot)
        .and_then(Option::take);
    let mut boxed = taken.unwrap_or_else(|| fail("ui state was read while it was being updated"));
    let result = match boxed.downcast_mut::<T>() {
        Some(value) => f(value),
        None => fail("ui_state hooks must run in the same order on every render"),
    };
    instance.hooks.borrow_mut()[slot] = Some(boxed);
    result
}

/// A handle to UI state created by [`PanelCx::ui_state`]. It is `Copy`, so
/// move it into as many handlers as needed. The host renders the panel again
/// after every event, so a change shows right away.
pub struct UiState<T> {
    instance: i32,
    slot: usize,
    _value: PhantomData<fn() -> T>,
}

impl<T> Clone for UiState<T> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<T> Copy for UiState<T> {}

impl<T: 'static> UiState<T> {
    /// A copy of the current value.
    pub fn get(&self) -> T
    where
        T: Clone,
    {
        self.with(T::clone)
    }

    /// Reads the current value without copying it.
    pub fn with<R>(&self, read: impl FnOnce(&T) -> R) -> R {
        with_hook(self.instance, self.slot, |value: &mut T| read(value))
    }

    /// Replaces the value.
    pub fn set(&self, value: T) {
        with_hook(self.instance, self.slot, |current: &mut T| *current = value);
    }

    /// Changes the value in place.
    pub fn update<R>(&self, change: impl FnOnce(&mut T) -> R) -> R {
        with_hook(self.instance, self.slot, change)
    }
}

/// The context of an event handler. Dereferences to [`Intents`], which
/// records what the host should change.
pub struct EventCx<'a> {
    intents: Intents,
    context: Context<'a>,
}

impl<'a> EventCx<'a> {
    /// The selected nodes the panel applies to, as of the last context.
    pub fn selection(&self) -> impl Iterator<Item = SelectedNode<'a>> {
        self.context.selection()
    }

    /// A prop of the panel's definition, as of the last context.
    pub fn prop(&self, name: &str) -> Field<'a> {
        self.context.prop(name)
    }

    /// A style key the panel declared, as of the last context.
    pub fn style(&self, key: &str) -> Field<'a> {
        self.context.style(key)
    }

    /// The state whose overrides are being edited, as of the last context.
    pub fn state_override(&self) -> Option<StateOverride<'a>> {
        self.context.state_override()
    }

    /// Where the selected nodes sit, as of the last context.
    pub fn layout(&self) -> Layout<'a> {
        self.context.layout()
    }

    /// Any context field by name, as of the last context.
    pub fn raw(&self, key: &str) -> &'a Value {
        self.context.get(key)
    }
}

impl Deref for EventCx<'_> {
    type Target = Intents;

    fn deref(&self) -> &Intents {
        &self.intents
    }
}

impl DerefMut for EventCx<'_> {
    fn deref_mut(&mut self) -> &mut Intents {
        &mut self.intents
    }
}

// The `vhp.panels` section ----------------------------------------------------------

/// The byte length of the `vhp.panels` section for `panels`: a JSON array of
/// their manifests.
pub const fn section_len(panels: &[&PanelDefinition]) -> usize {
    let mut length = 2;
    let mut index = 0;
    while index < panels.len() {
        length += panels[index].manifest.len();
        if index > 0 {
            length += 1;
        }
        index += 1;
    }
    length
}

/// The `vhp.panels` section for `panels`; `N` is [`section_len`].
pub const fn section_bytes<const N: usize>(panels: &[&PanelDefinition]) -> [u8; N] {
    let mut out = [0u8; N];
    out[0] = b'[';
    let mut at = 1;
    let mut index = 0;
    while index < panels.len() {
        if index > 0 {
            out[at] = b',';
            at += 1;
        }
        let bytes = panels[index].manifest.as_bytes();
        let mut byte = 0;
        while byte < bytes.len() {
            out[at] = bytes[byte];
            at += 1;
            byte += 1;
        }
        index += 1;
    }
    out[at] = b']';
    out
}

/// The section as a string, for tests on the build machine.
#[cfg(not(target_arch = "wasm32"))]
pub(crate) fn section_json(panels: &[&PanelDefinition]) -> alloc::string::String {
    let mut out = alloc::string::String::from("[");
    for (index, panel) in panels.iter().enumerate() {
        if index > 0 {
            out.push(',');
        }
        out.push_str(panel.manifest);
    }
    out.push(']');
    out
}
