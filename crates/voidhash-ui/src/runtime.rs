//! Component instances, state hooks and the calls the host makes.

use alloc::boxed::Box;
use alloc::rc::Rc;
use alloc::string::String;
use alloc::vec::Vec;
use core::any::Any;
use core::cell::{Cell, RefCell};
use core::marker::PhantomData;

use crate::canvas::{Frame, read_pointers};
use crate::host;
use crate::value::{Map, Value};
use crate::view::{Handler, Painter, View};

/// The handler id of events the host raises without one (timers).
const NO_HANDLER: i32 = -1;

/// The render function `#[component]` generates: decodes props and calls the
/// component.
pub type RenderFn = fn(Cx, &Value) -> View;

/// A component compiled into this module, generated by `#[component]`.
pub struct Component {
    /// The component's name in the manifest.
    pub name: &'static str,
    /// The manifest JSON embedded in the module's `vh.manifest` section.
    pub manifest: &'static str,
    /// Decodes props and renders the tree.
    pub render: RenderFn,
}

/// What the module is doing on behalf of the host. Actions that need a user
/// gesture are only sent during [`Phase::Event`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Phase {
    /// Not running component code (including `vh_mount`, `vh_update` and
    /// `vh_unmount`).
    Idle,
    /// Inside `vh_render`.
    Render,
    /// Inside `vh_event`.
    Event,
    /// Inside `vh_frame`.
    Frame,
}

struct Instance {
    props: RefCell<Rc<Value>>,
    hooks: RefCell<Vec<Option<Box<dyn Any>>>>,
    cursor: Cell<usize>,
    handlers: RefCell<Vec<Option<Handler>>>,
    painters: RefCell<Vec<Option<Painter>>>,
    /// Pointer ids that were down in the previous frame, per canvas.
    pointers: RefCell<Vec<(usize, Vec<i64>)>>,
    /// Pending host timers and the hook slot of the [`Cx::every`] each
    /// belongs to.
    timers: RefCell<Vec<(i32, usize)>>,
    /// The laid-out size the host reported last.
    layout: Cell<Option<(f32, f32)>>,
    dirty: Cell<bool>,
}

/// The state of a [`Cx::every`] hook.
struct Every {
    seconds: f64,
    enabled: bool,
    timer: Option<i32>,
    tick: Option<Tick>,
}

type Tick = Box<dyn FnMut(&mut EventCx<'_>)>;

struct Runtime {
    instances: Vec<Option<Rc<Instance>>>,
    /// Buffers handed out by `vh_alloc` that no call has consumed yet.
    #[cfg_attr(not(vh_guest), allow(dead_code))]
    inputs: Vec<Box<[u8]>>,
    /// The result of the last `vh_render` or `vh_frame`.
    output: Vec<u8>,
    phase: Phase,
}

impl Runtime {
    const fn new() -> Runtime {
        Runtime {
            instances: Vec::new(),
            inputs: Vec::new(),
            output: Vec::new(),
            phase: Phase::Idle,
        }
    }
}

#[cfg(any(vh_guest, vh_panel))]
mod global {
    use super::Runtime;
    use core::cell::RefCell;

    struct Single(RefCell<Runtime>);

    // SAFETY: component modules run on one thread; the host never calls into
    // an instance concurrently.
    unsafe impl Sync for Single {}

    static RUNTIME: Single = Single(RefCell::new(Runtime::new()));

    pub(super) fn with<R>(f: impl FnOnce(&mut Runtime) -> R) -> R {
        f(&mut RUNTIME.0.borrow_mut())
    }
}

#[cfg(not(any(vh_guest, vh_panel)))]
mod global {
    use super::Runtime;
    use core::cell::RefCell;

    std::thread_local! {
        static RUNTIME: RefCell<Runtime> = const { RefCell::new(Runtime::new()) };
    }

    pub(super) fn with<R>(f: impl FnOnce(&mut Runtime) -> R) -> R {
        RUNTIME.with(|runtime| f(&mut runtime.borrow_mut()))
    }
}

/// Stops the module: logs `message` and traps, so the host quarantines the
/// instance.
#[cold]
pub(crate) fn fail(message: &str) -> ! {
    host::log(3, message);
    #[cfg(any(vh_guest, vh_panel))]
    core::arch::wasm32::unreachable();
    #[cfg(not(any(vh_guest, vh_panel)))]
    panic!("{message}");
}

fn instance(id: i32) -> Rc<Instance> {
    let found = global::with(|runtime| {
        usize::try_from(id)
            .ok()
            .and_then(|index| runtime.instances.get(index))
            .and_then(Option::clone)
    });
    found.unwrap_or_else(|| fail("unknown component instance"))
}

pub(crate) fn phase() -> Phase {
    global::with(|runtime| runtime.phase)
}

fn set_phase(phase: Phase) {
    global::with(|runtime| runtime.phase = phase);
}

pub(crate) fn mark_dirty(id: i32) {
    instance(id).dirty.set(true);
}

// Host calls -----------------------------------------------------------------------

/// `vh_alloc`: a buffer of `size` bytes the host writes a call's input into.
#[cfg_attr(not(vh_guest), allow(dead_code))]
pub(crate) fn alloc(size: usize) -> *mut u8 {
    let mut buffer = alloc::vec![0u8; size.max(1)].into_boxed_slice();
    let pointer = buffer.as_mut_ptr();
    global::with(|runtime| runtime.inputs.push(buffer));
    pointer
}

/// Takes back the `vh_alloc` buffer at `pointer` once the host passes it to
/// a call. Input outside a buffer handed out by `vh_alloc` is rejected.
#[cfg_attr(not(vh_guest), allow(dead_code))]
pub(crate) fn take_input(pointer: *const u8, len: usize) -> Box<[u8]> {
    global::with(|runtime| {
        let index = runtime
            .inputs
            .iter()
            .position(|buffer| core::ptr::eq(buffer.as_ptr(), pointer) && len <= buffer.len());
        index.map(|index| runtime.inputs.swap_remove(index))
    })
    .unwrap_or_else(|| fail("call input was not allocated with vh_alloc"))
}

/// `vh_mount`: creates an instance and returns its id, or `-1` when the
/// props are not a valid encoded object.
pub(crate) fn mount(props: &[u8]) -> i32 {
    let props = match Value::decode(props) {
        Ok(props @ Value::Object(_)) => props,
        _ => return -1,
    };
    let instance = Rc::new(Instance {
        props: RefCell::new(Rc::new(props)),
        hooks: RefCell::new(Vec::new()),
        cursor: Cell::new(0),
        handlers: RefCell::new(Vec::new()),
        painters: RefCell::new(Vec::new()),
        pointers: RefCell::new(Vec::new()),
        timers: RefCell::new(Vec::new()),
        layout: Cell::new(None),
        dirty: Cell::new(false),
    });
    global::with(|runtime| {
        let id = runtime.instances.len();
        runtime.instances.push(Some(instance));
        i32::try_from(id).unwrap_or(-2)
    })
}

/// `vh_update`: replaces an instance's props. Invalid props trap.
pub(crate) fn update(id: i32, props: &[u8]) {
    let props = match Value::decode(props) {
        Ok(props @ Value::Object(_)) => props,
        _ => fail("vh_update props are not a valid encoded object"),
    };
    *instance(id).props.borrow_mut() = Rc::new(props);
}

/// `vh_render`: renders the instance and returns the encoded element tree.
pub(crate) fn render(id: i32, render: RenderFn) -> (*const u8, usize) {
    let instance = instance(id);
    let props = instance.props.borrow().clone();
    instance.cursor.set(0);
    set_phase(Phase::Render);
    let view = render(Cx { instance: id }, &props);
    let mut out = global::with(|runtime| core::mem::take(&mut runtime.output));
    out.clear();
    let mut handlers = Vec::new();
    let mut painters = Vec::new();
    view.encode(&mut out, &mut handlers, &mut painters, false);
    *instance.handlers.borrow_mut() = handlers;
    *instance.painters.borrow_mut() = painters;
    instance
        .pointers
        .borrow_mut()
        .retain(|(canvas, _)| *canvas < instance.painters.borrow().len());
    // Setting state while rendering does not schedule another render.
    instance.dirty.set(false);
    set_phase(Phase::Idle);
    finish_output(out)
}

/// `vh_event`: runs handler `handler` of the last tree, or the timer the
/// event names. Returns 1 when state changed and the tree must be rendered
/// again. Unknown handler ids (from a tree the host has not replaced yet) and
/// timers are ignored.
pub(crate) fn event(id: i32, handler: i32, event: &[u8]) -> i32 {
    let event =
        Value::decode(event).unwrap_or_else(|_| fail("vh_event input is not a valid value"));
    let instance = instance(id);
    if handler == NO_HANDLER {
        if event.get("type").and_then(Value::as_str) == Some("timer") {
            let timer = event.get("id").and_then(Value::as_f64).unwrap_or(-1.0) as i32;
            fire_timer(id, &instance, timer, &event);
        }
        return i32::from(instance.dirty.replace(false));
    }
    let index = usize::try_from(handler).unwrap_or(usize::MAX);
    let taken = instance
        .handlers
        .borrow_mut()
        .get_mut(index)
        .and_then(Option::take);
    let Some(mut action) = taken else {
        return 0;
    };
    set_phase(Phase::Event);
    action.handle(&mut EventCx {
        instance: id,
        event: &event,
    });
    set_phase(Phase::Idle);
    if let Some(slot) = instance.handlers.borrow_mut().get_mut(index) {
        *slot = Some(action);
    }
    i32::from(instance.dirty.replace(false))
}

/// Runs the [`Cx::every`] hook a fired timer belongs to and schedules its
/// next tick.
fn fire_timer(id: i32, instance: &Instance, timer: i32, event: &Value) {
    let slot = {
        let mut timers = instance.timers.borrow_mut();
        let Some(position) = timers.iter().position(|(pending, _)| *pending == timer) else {
            return;
        };
        timers.swap_remove(position).1
    };
    let tick = with_hook(id, slot, |every: &mut Every| {
        every.timer = None;
        every.tick.take()
    });
    if let Some(mut tick) = tick {
        set_phase(Phase::Event);
        tick(&mut EventCx {
            instance: id,
            event,
        });
        set_phase(Phase::Idle);
        with_hook(id, slot, |every: &mut Every| {
            if every.tick.is_none() {
                every.tick = Some(tick);
            }
        });
    }
    schedule_every(id, instance, slot);
}

/// Keeps an enabled [`Cx::every`] hook's timer pending and cancels a
/// disabled one's.
fn schedule_every(id: i32, instance: &Instance, slot: usize) {
    let (enabled, seconds, timer) = with_hook(id, slot, |every: &mut Every| {
        (every.enabled, every.seconds, every.timer)
    });
    match (enabled, timer) {
        (true, None) => {
            let timer = host::schedule(id, seconds);
            if timer >= 0 {
                with_hook(id, slot, |every: &mut Every| every.timer = Some(timer));
                instance.timers.borrow_mut().push((timer, slot));
            }
        }
        (false, Some(timer)) => {
            host::cancel(timer);
            with_hook(id, slot, |every: &mut Every| every.timer = None);
            instance
                .timers
                .borrow_mut()
                .retain(|(pending, _)| *pending != timer);
        }
        _ => {}
    }
}

/// `vh_layout` (ABI 2): records the instance's laid-out size and renders
/// again when it changed.
pub(crate) fn layout(id: i32, width: f64, height: f64) {
    let instance = instance(id);
    let size = Some((width as f32, height as f32));
    if instance.layout.replace(size) != size {
        host::invalidate(id);
    }
}

/// `vh_frame`: advances canvas `canvas` by `dt` seconds and returns its draw
/// list. Unknown canvas ids draw nothing. When the frame changed state the
/// host is asked to render again with `vh.invalidate`.
pub(crate) fn frame(id: i32, canvas: i32, dt: f64, input: &[u8]) -> (*const u8, usize) {
    let input =
        Value::decode(input).unwrap_or_else(|_| fail("vh_frame input is not a valid value"));
    let instance = instance(id);
    let index = usize::try_from(canvas).unwrap_or(usize::MAX);
    let mut out = global::with(|runtime| core::mem::take(&mut runtime.output));
    out.clear();
    let taken = instance
        .painters
        .borrow_mut()
        .get_mut(index)
        .and_then(Option::take);
    if let Some(mut draw) = taken {
        let pointers = {
            let mut memory = instance.pointers.borrow_mut();
            let position = match memory.iter().position(|(existing, _)| *existing == index) {
                Some(position) => position,
                None => {
                    memory.push((index, Vec::new()));
                    memory.len() - 1
                }
            };
            read_pointers(&input, &mut memory[position].1)
        };
        let number = |key| input.get(key).and_then(Value::as_f64).unwrap_or(0.0) as f32;
        set_phase(Phase::Frame);
        draw(&mut Frame {
            instance: id,
            dt: dt as f32,
            width: number("width"),
            height: number("height"),
            pointers: &pointers,
            out: &mut out,
        });
        set_phase(Phase::Idle);
        if let Some(slot) = instance.painters.borrow_mut().get_mut(index) {
            *slot = Some(draw);
        }
        if instance.dirty.replace(false) {
            host::invalidate(id);
        }
    }
    finish_output(out)
}

/// `vh_unmount`: frees the instance and its state.
pub(crate) fn unmount(id: i32) {
    let removed = global::with(|runtime| {
        usize::try_from(id)
            .ok()
            .and_then(|index| runtime.instances.get_mut(index))
            .and_then(Option::take)
    });
    // State and closures drop here, outside the runtime borrow.
    drop(removed);
}

fn finish_output(out: Vec<u8>) -> (*const u8, usize) {
    let result = (out.as_ptr(), out.len());
    global::with(|runtime| runtime.output = out);
    result
}

// Actions --------------------------------------------------------------------------

fn send(action: Value) -> bool {
    host::action(&action.to_bytes())
}

fn typed(kind: &str) -> Map {
    let mut map = Map::new();
    map.insert("type", kind);
    map
}

pub(crate) fn emit(name: &str, payload: Value) -> bool {
    let mut action = typed("emit");
    action.insert("name", name);
    action.insert("payload", payload);
    send(Value::Object(action))
}

pub(crate) fn track(name: &str, properties: Value) -> bool {
    let mut action = typed("track");
    action.insert("name", name);
    action.insert("properties", properties);
    send(Value::Object(action))
}

// Contexts -------------------------------------------------------------------------

/// The render context of a component instance: state hooks and host
/// services.
#[derive(Clone, Copy, Debug)]
pub struct Cx {
    instance: i32,
}

impl Cx {
    fn hook<T: 'static>(&self, init: impl FnOnce() -> T) -> usize {
        let instance = instance(self.instance);
        let slot = instance.cursor.get();
        instance.cursor.set(slot + 1);
        let existing = instance
            .hooks
            .borrow()
            .get(slot)
            .map(|hook| hook.as_ref().is_some_and(|value| value.is::<T>()));
        match existing {
            Some(true) => {}
            Some(false) => fail("state hooks must run in the same order on every render"),
            None => {
                let value: Box<dyn Any> = Box::new(init());
                instance.hooks.borrow_mut().push(Some(value));
            }
        }
        slot
    }

    /// State that persists across renders. `init` runs on the first render
    /// only. Changing it renders the component again.
    ///
    /// Like hooks in React, call `state` unconditionally and in the same
    /// order on every render.
    pub fn state<T: 'static>(&self, init: impl FnOnce() -> T) -> State<T> {
        State {
            instance: self.instance,
            slot: self.hook(init),
            _value: PhantomData,
        }
    }

    /// A value that persists across renders without rendering again when it
    /// changes, for per-frame data such as a game's positions.
    pub fn store<T: 'static>(&self, init: impl FnOnce() -> T) -> Store<T> {
        Store {
            instance: self.instance,
            slot: self.hook(init),
            _value: PhantomData,
        }
    }

    /// The preview state the designer asked for (the reserved `$state`
    /// prop), if any.
    pub fn preview_state(&self) -> Option<String> {
        instance(self.instance)
            .props
            .borrow()
            .get("$state")
            .and_then(Value::as_str)
            .map(String::from)
    }

    /// Seconds since the instance mounted.
    pub fn now(&self) -> f64 {
        host::now()
    }

    /// A random number in `[0, 1)`.
    pub fn random(&self) -> f64 {
        host::random()
    }

    /// Asks the host to render this instance again: after the current event
    /// or frame, or right away otherwise.
    pub fn invalidate(&self) {
        match phase() {
            Phase::Event | Phase::Frame => mark_dirty(self.instance),
            _ => host::invalidate(self.instance),
        }
    }

    /// Writes an informational message to the host's log.
    pub fn log(&self, message: &str) {
        host::log(1, message);
    }

    /// Runs `tick` every `seconds` while `enabled`, as a host timer: no code
    /// runs between ticks. Like [`Cx::state`], call it unconditionally and
    /// in the same order on every render; pass `enabled = false` to stop.
    /// Ticks are not user input, so they cannot purchase.
    pub fn every<F, R>(&self, seconds: f64, enabled: bool, mut tick: F)
    where
        F: FnMut(&mut EventCx<'_>) -> R + 'static,
    {
        let slot = self.hook(|| Every {
            seconds,
            enabled,
            timer: None,
            tick: None,
        });
        with_hook(self.instance, slot, |every: &mut Every| {
            every.seconds = seconds.max(0.0);
            every.enabled = enabled;
            every.tick = Some(Box::new(move |cx| {
                tick(cx);
            }));
        });
        schedule_every(self.instance, &instance(self.instance), slot);
    }

    /// The instance's laid-out size in logical pixels, once the host
    /// reported it (ABI 2). The component renders again when it changes.
    pub fn layout(&self) -> Option<(f32, f32)> {
        instance(self.instance).layout.get()
    }

    /// Whether the flow disabled the component (the reserved `$disabled`
    /// prop, ABI 3). The host delivers it no presses, pointers or typing
    /// while it is; draw it so.
    pub fn disabled(&self) -> bool {
        instance(self.instance)
            .props
            .borrow()
            .get("$disabled")
            .and_then(Value::as_bool)
            .unwrap_or(false)
    }

    /// Says whether the component's value is valid (ABI 3), which the
    /// flow's `is-valid` conditions and the component's `invalid` state
    /// read. A value is valid until the component says otherwise. Unlike
    /// setting the value, this needs no event of the end user's, so a
    /// component can report it while rendering.
    pub fn set_validity(&self, valid: bool) -> bool {
        set_validity(valid)
    }

    /// Writes a prop the component computes (`#[prop(computed)]`, guest
    /// ABI 4) to whatever the instance bound it to: an output, such as
    /// whether what it holds is valid, which it may write at any time, on
    /// its first render too. Returns whether the host took it.
    pub fn set_prop(&self, prop: &str, value: impl Into<Value>) -> bool {
        set_prop(prop, value.into())
    }

    /// The host context the reserved `$context` prop carries (ABI 2).
    fn context(&self, key: &str) -> Option<Value> {
        instance(self.instance)
            .props
            .borrow()
            .get("$context")
            .and_then(|context| context.get(key))
            .cloned()
    }

    /// The paywall's locale, such as `en-US`, when the host knows it.
    pub fn locale(&self) -> Option<String> {
        self.context("locale")
            .and_then(|locale| locale.as_str().map(String::from))
    }

    /// Whether the user asked for reduced motion.
    pub fn reduced_motion(&self) -> bool {
        self.context("reducedMotion")
            .and_then(|flag| flag.as_bool())
            .unwrap_or(false)
    }

    /// Whether the paywall shows in dark mode (`"dark"`) or light mode
    /// (`"light"`).
    pub fn color_scheme(&self) -> String {
        self.context("colorScheme")
            .and_then(|scheme| scheme.as_str().map(String::from))
            .unwrap_or_else(|| String::from("light"))
    }
}

fn with_hook<T: 'static, R>(instance_id: i32, slot: usize, f: impl FnOnce(&mut T) -> R) -> R {
    let instance = instance(instance_id);
    let taken = instance
        .hooks
        .borrow_mut()
        .get_mut(slot)
        .and_then(Option::take);
    let mut boxed = taken.unwrap_or_else(|| fail("state was read while it was being updated"));
    let result = match boxed.downcast_mut::<T>() {
        Some(value) => f(value),
        None => fail("state hooks must run in the same order on every render"),
    };
    instance.hooks.borrow_mut()[slot] = Some(boxed);
    result
}

/// A handle to component state created by [`Cx::state`]. It is `Copy`, so
/// move it into as many closures as needed.
pub struct State<T> {
    instance: i32,
    slot: usize,
    _value: PhantomData<fn() -> T>,
}

impl<T> Clone for State<T> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<T> Copy for State<T> {}

impl<T: 'static> State<T> {
    /// A copy of the current value.
    pub fn get(&self) -> T
    where
        T: Clone,
    {
        self.with(T::clone)
    }

    /// Reads the current value without copying it.
    pub fn with<R>(&self, read: impl FnOnce(&T) -> R) -> R {
        with_hook(self.instance, self.slot, |value: &mut T| read(value))
    }

    /// Replaces the value. The component renders again if it changed.
    pub fn set(&self, value: T)
    where
        T: PartialEq,
    {
        let changed = with_hook(self.instance, self.slot, |current: &mut T| {
            if *current == value {
                false
            } else {
                *current = value;
                true
            }
        });
        if changed {
            mark_dirty(self.instance);
        }
    }

    /// Changes the value in place. The component renders again.
    pub fn update<R>(&self, change: impl FnOnce(&mut T) -> R) -> R {
        let result = with_hook(self.instance, self.slot, change);
        mark_dirty(self.instance);
        result
    }
}

/// A handle to a value created by [`Cx::store`]. Changing it does not
/// render the component again.
pub struct Store<T> {
    instance: i32,
    slot: usize,
    _value: PhantomData<fn() -> T>,
}

impl<T> Clone for Store<T> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<T> Copy for Store<T> {}

impl<T: 'static> Store<T> {
    /// A copy of the current value.
    pub fn get(&self) -> T
    where
        T: Clone,
    {
        self.with(T::clone)
    }

    /// Reads the current value without copying it.
    pub fn with<R>(&self, read: impl FnOnce(&T) -> R) -> R {
        with_hook(self.instance, self.slot, |value: &mut T| read(value))
    }

    /// Replaces the value.
    pub fn set(&self, value: T) {
        with_hook(self.instance, self.slot, |current: &mut T| *current = value);
    }

    /// Changes the value in place.
    pub fn update<R>(&self, change: impl FnOnce(&mut T) -> R) -> R {
        with_hook(self.instance, self.slot, change)
    }
}

/// The context of an event handler (see [`View::on_tap`]). Purchases and
/// other actions that need a user gesture are only available here.
pub struct EventCx<'a> {
    instance: i32,
    event: &'a Value,
}

impl EventCx<'_> {
    /// The event, for example `{"type": "press"}`.
    pub fn event(&self) -> &Value {
        self.event
    }

    /// Starts a purchase of the product. Returns whether the host accepted
    /// the request; the purchase itself completes asynchronously.
    pub fn purchase(&mut self, product_id: &str) -> bool {
        let mut action = typed("purchase");
        action.insert("productId", product_id);
        send(Value::Object(action))
    }

    /// Restores previous purchases.
    pub fn restore(&mut self) -> bool {
        send(Value::Object(typed("restore")))
    }

    /// Closes the paywall or flow.
    pub fn close(&mut self) -> bool {
        send(Value::Object(typed("close")))
    }

    /// Opens a link.
    pub fn open_url(&mut self, url: &str) -> bool {
        let mut action = typed("openUrl");
        action.insert("url", url);
        send(Value::Object(action))
    }

    /// Records an analytics event with its properties (an object or null).
    pub fn track(&mut self, name: &str, properties: Value) -> bool {
        track(name, properties)
    }

    /// Fires one of the component's declared actions, which the paywall
    /// binds to behaviour such as a purchase or navigation.
    pub fn emit(&mut self, name: &str, payload: Value) -> bool {
        emit(name, payload)
    }

    /// Seconds since the instance mounted.
    pub fn now(&self) -> f64 {
        host::now()
    }

    /// A random number in `[0, 1)`.
    pub fn random(&self) -> f64 {
        host::random()
    }

    /// Renders the component again after this event even if no state
    /// changed.
    pub fn invalidate(&mut self) {
        mark_dirty(self.instance);
    }

    /// Says the end user started changing the component's value (ABI 3):
    /// the flow runs the `focus` interactions of the component and puts it
    /// in its `focused` state. A drag calls it when the pointer goes down.
    pub fn begin_editing(&mut self) -> bool {
        editing(true)
    }

    /// Says the end user finished changing the value: the flow runs `blur`,
    /// and from then on shows the component as invalid when it is.
    pub fn end_editing(&mut self) -> bool {
        editing(false)
    }

    /// Says the end user confirmed the value: the flow runs `submit`.
    pub fn submit(&mut self) -> bool {
        send(Value::Object(typed("submit")))
    }

    /// Says whether the component's value is valid; see [`Cx::set_validity`].
    pub fn set_validity(&mut self, valid: bool) -> bool {
        set_validity(valid)
    }

    /// Writes a prop the component writes (`#[prop(writes)]`) or computes
    /// (`#[prop(computed)]`), guest ABI 4. The write goes where the
    /// instance sends it: the variable the prop is bound to, else the
    /// instance's own copy of the prop; one bound to what cannot be written
    /// is dropped and the prop keeps reading its source. Like a value, a
    /// written prop is taken only while the end user acts on the component.
    /// The component renders again with the new prop. Returns whether the
    /// host took it.
    pub fn set_prop(&mut self, prop: &str, value: impl Into<Value>) -> bool {
        set_prop(prop, value.into())
    }

    /// Asks for the keyboard for the component's first
    /// [`text_input`](crate::view::text_input) (ABI 3).
    pub fn focus_text(&mut self) -> bool {
        send(Value::Object(typed("focusText")))
    }

    /// Asks for the keyboard for the [`text_input`](crate::view::text_input)
    /// with this [`key`](crate::View::key).
    pub fn focus_text_keyed(&mut self, key: &str) -> bool {
        let mut action = typed("focusText");
        action.insert("key", key);
        send(Value::Object(action))
    }

    /// Gives up the keyboard, if one of the component's text inputs has it.
    pub fn blur_text(&mut self) -> bool {
        send(Value::Object(typed("blurText")))
    }
}

fn editing(active: bool) -> bool {
    let mut action = typed("editing");
    action.insert("active", active);
    send(Value::Object(action))
}

fn set_prop(prop: &str, value: Value) -> bool {
    let mut action = typed("set");
    action.insert("prop", prop);
    action.insert("value", value);
    send(Value::Object(action))
}

fn set_validity(valid: bool) -> bool {
    let mut action = typed("validity");
    action.insert("valid", valid);
    send(Value::Object(action))
}

// The component's value --------------------------------------------------------------

/// A type a component's value can have: `String`, `f64`, `bool`, or
/// `Vec<String>` for a list (ordered strings without repeats, at most 100 of
/// at most 200 characters).
pub trait InputValue: Clone + Default + 'static {
    /// The value type of the component definition (`string`, `number`,
    /// `boolean` or `list`).
    const TYPE: &'static str;
    /// Reads the value, or `None` when it has another type.
    fn from_value(value: &Value) -> Option<Self>;
    /// The value as the host takes it.
    fn into_value(self) -> Value;
}

impl InputValue for String {
    const TYPE: &'static str = "string";
    fn from_value(value: &Value) -> Option<Self> {
        value.as_str().map(String::from)
    }
    fn into_value(self) -> Value {
        Value::from(self)
    }
}

impl InputValue for f64 {
    const TYPE: &'static str = "number";
    fn from_value(value: &Value) -> Option<Self> {
        value.as_f64()
    }
    fn into_value(self) -> Value {
        Value::from(self)
    }
}

impl InputValue for bool {
    const TYPE: &'static str = "boolean";
    fn from_value(value: &Value) -> Option<Self> {
        value.as_bool()
    }
    fn into_value(self) -> Value {
        Value::from(self)
    }
}

/// A list: `$value` carries it as an array of strings. The host takes a list
/// without repeats of at most 100 strings of at most 200 characters, and
/// ignores any other.
impl InputValue for Vec<String> {
    const TYPE: &'static str = "list";
    fn from_value(value: &Value) -> Option<Self> {
        value
            .as_array()?
            .iter()
            .map(|item| item.as_str().map(String::from))
            .collect()
    }
    fn into_value(self) -> Value {
        Value::from(self)
    }
}

/// The value a component owns, which makes it an input: a flow binds it to
/// a variable both ways (ABI 3). A component takes it as the parameter
/// marked `#[value]`:
///
/// ```ignore
/// #[component]
/// pub fn Toggle(cx: Cx, #[value] on: Input<bool>) -> View {
///     let now = on.get();
///     view().on_tap(move |cx| on.set(cx, !now))
/// }
/// ```
///
/// [`Input::get`] is the value now, whoever set it last: the component, an
/// action of the flow or the app. [`Input::set`] writes the variable and
/// runs the component's `change` interactions; the component renders again
/// with the new value.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Input<T> {
    value: T,
}

impl<T: InputValue> Input<T> {
    /// Reads the reserved `$value` prop. Used by `#[component]`.
    #[doc(hidden)]
    pub fn read(props: &Value) -> Input<T> {
        Input {
            value: props
                .get("$value")
                .and_then(T::from_value)
                .unwrap_or_default(),
        }
    }

    /// The value now.
    pub fn get(&self) -> T {
        self.value.clone()
    }

    /// Sets the value. Like a purchase, the host takes it only during an
    /// event of the end user's (a press, a pointer, typing, an
    /// accessibility action) and ignores it otherwise; returns whether it
    /// took it.
    pub fn set(&self, _cx: &mut EventCx<'_>, value: T) -> bool {
        let mut action = typed("value");
        action.insert("value", value.into_value());
        send(Value::Object(action))
    }
}

impl<T> core::ops::Deref for Input<T> {
    type Target = T;

    fn deref(&self) -> &T {
        &self.value
    }
}

// Text size. Kept at the end of the file: a component's module records where
// in this file its panics are, so code added above would change the bytes of
// every component built with it.
impl Cx {
    /// The end user's text size as a multiple of the designed size (iOS
    /// Dynamic Type, Android's font size): 1 at the default size, about 3 at
    /// iOS's largest. It is 1 in a flow built before flows followed the text
    /// size and on a runtime or host that does not report it. A component
    /// whose definition says `follows_text_size` has its text elements sized
    /// for it by the runtime; any component sizes from it what it draws
    /// itself and the boxes it holds text in.
    pub fn font_scale(&self) -> f32 {
        self.context("fontScale")
            .and_then(|scale| scale.as_f64())
            .filter(|scale| scale.is_finite() && *scale > 0.0)
            .map_or(1.0, |scale| scale as f32)
    }
}
